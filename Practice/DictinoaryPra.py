# Stores data as  - - key : value - -

# Keys must be unique.

# student = {
#     "name": "John",
#     "age": 20
# }

# | Function       | Description               |
# | -------------- | ------------------------- |
# | `get(key)`     | Get value safely          |
# | `keys()`       | All keys                  |
# | `values()`     | All values                |
# | `items()`      | Key-value pairs           |
# | `update()`     | Merge dictionary          |
# | `pop(key)`     | Remove key                |
# | `popitem()`    | Remove last inserted item |
# | `clear()`      | Empty dictionary          |
# | `copy()`       | Copy dictionary           |
# | `setdefault()` | Insert default value      |
